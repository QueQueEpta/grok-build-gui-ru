  let activeLocale = "ru";

  function interpolate(text, vars = {}) {
    return String(text).replace(/\{(\w+)\}/g, (_match, key) => (vars[key] != null ? String(vars[key]) : `{${key}}`));
  }

  function t(key, vars) {
    const table = locales[activeLocale] || locales.ru;
    const fallback = locales.ru[key];
    const value = table[key] ?? fallback ?? key;
    return interpolate(value, vars);
  }

  function getLocale() {
    return activeLocale;
  }

  function setLocale(locale) {
    activeLocale = Object.hasOwn(locales, locale) ? locale : "ru";
    document.documentElement.lang = activeLocale;
  }

  function applyDom(root = document) {
    root.querySelectorAll("[data-i18n]").forEach((node) => {
      node.textContent = t(node.dataset.i18n);
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
      node.placeholder = t(node.dataset.i18nPlaceholder);
    });
    root.querySelectorAll("[data-i18n-title]").forEach((node) => {
      node.title = t(node.dataset.i18nTitle);
    });
    root.querySelectorAll("[data-i18n-aria]").forEach((node) => {
      node.setAttribute("aria-label", t(node.dataset.i18nAria));
    });
    const themeSelect = root.querySelector ? root.querySelector("#themeSelect") : null;
    if (themeSelect) {
      for (const option of themeSelect.options) {
        const key = option.dataset.i18nOption;
        if (key) option.textContent = t(key);
      }
    }
    const localeSelect = root.querySelector ? root.querySelector("#localeSelect") : null;
    if (localeSelect) {
      for (const option of localeSelect.options) {
        const key = option.dataset.i18nOption;
        if (key) option.textContent = t(key);
      }
    }
  }

  function mergeLocales(extra) {
    for (const locale of Object.keys(extra)) {
      locales[locale] = { ...locales[locale], ...extra[locale] };
    }
  }

  window.GrokI18n = { locales, t, getLocale, setLocale, applyDom, mergeLocales };
